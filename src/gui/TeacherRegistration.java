    private void loadTeachers() {

        try {

            ResultSet resultSet = MySQLClass.executeSearch("SELECT * FROM `teacher` "
                    + " ORDER BY `id` ASC ;");

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> v = new Vector();

//                String fname = resultSet.getString("f_name");
//                String lname = resultSet.getString("l_name");
                v.add(resultSet.getString("id"));
                v.add(resultSet.getString("f_name"));
                v.add(resultSet.getString("l_name"));
                v.add(resultSet.getString("email"));
                v.add(resultSet.getString("address"));
                v.add(resultSet.getString("city"));
                v.add(resultSet.getString("mobile"));
                v.add(resultSet.getString("nic"));

                model.addRow(v);
                jTable1.setModel(model);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }

