    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String fname = jTextField1.getText();
        String lname = jTextField2.getText();
        String email = jTextField3.getText();
        String addr = jTextField4.getText();
        String city = jTextField5.getText();
        String mobile = jTextField6.getText();
        String nic = jTextField7.getText();

        if (fname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter first name", "Warning!!!", JOptionPane.WARNING_MESSAGE);

        } else if (lname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter last name", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter email", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else if (addr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter address", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else if (city.isEmpty()) {
            JOptionPane.showMessageDialog(this, "please enter city", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else if (mobile.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter mobile", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else if (nic.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter NIC", "Warning!!!", JOptionPane.WARNING_MESSAGE);
        } else {

            try {
                MySQLClass.executeIUD("INSERT INTO `teacher`(`f_name`,`l_name`,`email`,`mobile`,`nic`,`address`,`city`) "
                        + "VALUES('" + fname + "','" + lname + "','" + email + "','" + mobile + "','" + nic + "','" + addr + "','" + city + "')");
                reset();
            } catch (Exception e) {
                e.printStackTrace();
            }

        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        int selectedRow = jTable1.getSelectedRow();
        String id = String.valueOf(jTable1.getValueAt(selectedRow, 0));

        String fname = jTextField1.getText();
        String lname = jTextField2.getText();
        String email = jTextField3.getText();
        String addr = jTextField4.getText();
        String city = jTextField5.getText();
        String mobile = jTextField6.getText();
        String nic = jTextField7.getText();

        try {
            MySQLClass.executeIUD("UPDATE `teacher` SET `f_name`='" + fname + "', "
                    + "`l_name`='" + lname + "', "
                    + "`mobile`='" + mobile + "', "
                    + "`email`='" + email + "', "
                    + "`nic`='" + nic + "', "
                    + "`address`='" + addr + "', "
                    + "`city`='" + city + "' "
                    + "WHERE `id`='" + id + "'");

            jTable1.setEnabled(true);
            loadTeachers();
            reset();
        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton2ActionPerformed

