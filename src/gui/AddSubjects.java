    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        
        int row = jTable1.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please Select a Row", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            String id = String.valueOf(jTable1.getValueAt(row, 0));
            String subject = String.valueOf(jTable1.getValueAt(row, 1));
            String description = String.valueOf(jTable1.getValueAt(row, 2));
            
            jLabel4.setText(id);
            jTextField1.setText(subject);
            jTextField2.setText(description);

            jButton1.setEnabled(false);

        }

        
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String name = jTextField1.getText();
        String description = jTextField2.getText();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Subject Name", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (description.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Subject Description", "Warning", JOptionPane.WARNING_MESSAGE);

        } else {

            try {

                    MySQLClass.executeIUD("INSERT INTO `subject`(`name`,`description`) "
                        + "VALUES('" + name + "','" + description + "')");

                    JOptionPane.showMessageDialog(this, "Subject was added succesfully", "Success", JOptionPane.INFORMATION_MESSAGE);

                    reset();

            } catch (Exception e) {
                e.printStackTrace();
            }

        }


    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
        int row = jTable1.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Please Select a Row", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            
            String id = jLabel4.getText();
            String subject = jTextField1.getText();
            String description = jTextField2.getText();

            if (subject.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please Enter Subject Name", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (description.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please Enter Description", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                try {

                    ResultSet resultSet = MySQLClass.executeSearch("SELECT * FROM `subject` WHERE `id` = '" + id + "'");

                    if (!resultSet.next()) {
                        JOptionPane.showMessageDialog(this, "The Subject is already exists", "Warning", JOptionPane.WARNING_MESSAGE);
                    } else {

                        MySQLClass.executeIUD("UPDATE `subject` SET `name` = '" + subject + "', `description` = '" + description + "' WHERE `id` = '" + id + "'");

                        JOptionPane.showMessageDialog(this, "The Subject is updated succesfully", "Success", JOptionPane.INFORMATION_MESSAGE);

                        reset();

                    }

                } catch (Exception e) {
                    e.printStackTrace();
                }

            }

        }
        
    }//GEN-LAST:event_jButton2ActionPerformed

